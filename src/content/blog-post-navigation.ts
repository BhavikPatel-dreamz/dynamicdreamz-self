const canonicalNavMap = new Map<
  string,
  { previous: BlogPostNavigationItem | null; next: BlogPostNavigationItem | null }
>();

for (let i = 0; i < blogPostChronologicalNavItems.length; i++) {
  const current = blogPostChronologicalNavItems[i];
  const previous = i > 0 ? blogPostChronologicalNavItems[i - 1] : null;
  const next =
    i < blogPostChronologicalNavItems.length - 1
      ? blogPostChronologicalNavItems[i + 1]
      : null;
  canonicalNavMap.set(current.slug, { previous, next });
}

export function resolveBlogPostNavigation(
  slug: string,
  explicit?: {
    previous?: BlogPostNavigationItem | null;
    next?: BlogPostNavigationItem | null;
  },
  dynamicList?: Array<BlogPostNavigationItem>,
): {
  previous: BlogPostNavigationItem | null;
  next: BlogPostNavigationItem | null;
} {
  if (
    explicit?.previous !== undefined &&
    explicit?.previous !== null &&
    explicit?.next !== undefined &&
    explicit?.next !== null
  ) {
    return {
      previous: explicit.previous,
      next: explicit.next,
    };
  }

  if (dynamicList && dynamicList.length > 0) {
    const idx = dynamicList.findIndex((item) => item.slug === slug);
    if (idx !== -1) {
      const dynamicPrev = idx > 0 ? dynamicList[idx - 1] : null;
      const dynamicNext =
        idx < dynamicList.length - 1 ? dynamicList[idx + 1] : null;
      return {
        previous: explicit?.previous ?? dynamicPrev,
        next: explicit?.next ?? dynamicNext,
      };
    }
  }

  const canonical = canonicalNavMap.get(slug);
  return {
    previous: explicit?.previous ?? canonical?.previous ?? null,
    next: explicit?.next ?? canonical?.next ?? null,
  };
}
